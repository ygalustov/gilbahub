    function exportReport() {
        if (typeof global.docx === 'undefined') {
            alert('Word export library not loaded. Please refresh the page and try again.');
            return;
        }

        var D = global.docx;
        var rigData      = global.GSSH_LAST_RIG_RESULT || null;
        var seasonalData = global.GSSH_LAST_SEASONAL_RESULT || null;
        var eue          = global.GSSH_EUE_Bridge ? global.GSSH_EUE_Bridge.getLastEUE() : null;
        var gaipState    = global.GAIP_STATE || null;
        var venue        = (rigData && rigData.venue) ||
                          (seasonalData && seasonalData.venue) ||
                          (global.GSSH_UnifiedVenueSelector ? global.GSSH_UnifiedVenueSelector.getCurrentVenue() : null);

        if (!rigData && !seasonalData && !eue) {
            alert('No LED analysis data found. Please run the Rig Calculator and/or Seasonal Planner first.');
            return;
        }

        // Build all sections
        var children = [].concat(
            buildCover(venue, rigData, eue),
            [heading1('1. Summary'), kv('Venue', (venue && venue.name) || '-'), kv('Date', today()), kv('Rig Model', (rigData && rigData.rigModel) || (seasonalData && seasonalData.rigModel) || '-'), divider()],
            buildEUESection(eue),
            [new D.Paragraph({ children: [new D.PageBreak()], spacing: { before: 0, after: 0 } })],
            buildRigSection(rigData, gaipState),
            [new D.Paragraph({ children: [new D.PageBreak()], spacing: { before: 0, after: 0 } })],
            buildSeasonalSection(seasonalData),
            [new D.Paragraph({ children: [new D.PageBreak()], spacing: { before: 0, after: 0 } })],
            buildAgronomicSection(gaipState, eue),
            buildDisclaimer()
        );

        var venueName = (venue && venue.name) || 'Venue';

        var PageNumber = D.PageNumber;

        var doc = new D.Document({
            creator:     'Gilba Agronomic Intelligence Hub',
            title:       'LED Lighting Technical Report, ' + venueName,
            description: 'Generated by GAIP Hub v' + VERSION,
            styles: {
                default: {
                    document: {
                        run: { font: 'Calibri', size: 22, color: COLOURS.textDark }
                    }
                }
            },
            sections: [{
                properties: {
                    page: {
                        margin: { top: 1000, bottom: 1000, left: 1100, right: 1100 }
                    }
                },
                headers: {
                    default: new D.Header({
                        children: [new D.Paragraph({
                            children: [
                                new D.TextRun({ text: 'Gilba Solutions, LED Technical Report', bold: true, size: 18, color: COLOURS.gilbaGreen, font: 'Calibri' }),
                                new D.TextRun({ text: '    |    ' + venueName, size: 18, color: COLOURS.textMid, font: 'Calibri' })
                            ],
                            border: { bottom: { style: D.BorderStyle.SINGLE, size: 4, color: COLOURS.gilbaGreen } }
                        })]
                    })
                },
                footers: {
                    default: new D.Footer({
                        children: [new D.Paragraph({
                            alignment: D.AlignmentType.CENTER,
                            children: [
                                new D.TextRun({ text: 'www.gilba.com.au  |  GAIP Hub v' + VERSION + '  |  Generated ' + today() + '  |  Page ', size: 16, color: COLOURS.textLight, font: 'Calibri' }),
                                new D.TextRun({ children: [PageNumber.CURRENT], size: 16, color: COLOURS.textLight, font: 'Calibri' })
                            ],
                            border: { top: { style: D.BorderStyle.SINGLE, size: 4, color: COLOURS.border } }
                        })]
                    })
                },
                children: children
            }]
        });

        D.Packer.toBlob(doc).then(function(blob) {
            var fname = 'LED_Report_' + venueName.replace(/[^a-zA-Z0-9]/g, '_') + '_' + new Date().toISOString().slice(0, 10) + '.docx';
            var url = URL.createObjectURL(blob);
            var a   = document.createElement('a');
            a.href  = url;
            a.download = fname;
            document.body.appendChild(a);
            a.click();
            document.body.removeChild(a);
            setTimeout(function() { URL.revokeObjectURL(url); }, 2000);
            console.log('[LEDExport] Downloaded:', fname);
        }).catch(function(err) {
            console.error('[LEDExport] Failed:', err);
            alert('Export failed: ' + err.message);
        });
    }

